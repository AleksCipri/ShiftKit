"""
Example: node-level domain adaptation on two PyG graphs (one per domain).

Uses DataManager.load("pyg_domains") with stratified node masks and
shiftkit.models.GNN with pool="none".

Both graphs are generated by the same labelling rule:
  - every node gets a class c in {0, ..., K-1} (balanced, shuffled);
  - node features are drawn around a class-specific mean, so features carry
    class signal (``class_sep`` controls how much);
  - edges are homophilous: same-class pairs connect with probability ``p_in``,
    different-class pairs with ``p_out`` < ``p_in``.
The target graph uses the same rule with a different seed and its features
translated by ``shift`` in every dimension (the domain shift).

Run from repo root (CPU, ~seconds):
    python examples/pyg_node_mmd.py
"""

import sys
import os
import json
import random

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))

import numpy as np
import torch
from torch_geometric.data import Data

from shiftkit.data import DataManager
from shiftkit.models import GNN
from shiftkit.methods import MMDTrainer, SourceOnlyTrainer


def set_seed(seed: int) -> None:
    """Seed Python, NumPy and PyTorch RNGs (model init, shuffling)."""
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)


def make_class_means(n_classes: int, feat_dim: int, class_sep: float, seed: int) -> torch.Tensor:
    """Class-specific feature means, shared by source and target."""
    g = torch.Generator().manual_seed(seed)
    means = torch.randn(n_classes, feat_dim, generator=g)
    return class_sep * means / means.norm(dim=1, keepdim=True)


def make_domain_graph(
    n_nodes: int,
    class_means: torch.Tensor,
    seed: int,
    shift: float = 0.0,
    p_in: float = 0.05,
    p_out: float = 0.005,
) -> Data:
    """Homophilous graph with class-dependent features (shared labelling rule)."""
    g = torch.Generator().manual_seed(seed)
    n_classes, feat_dim = class_means.shape
    y = torch.arange(n_nodes) % n_classes
    y = y[torch.randperm(n_nodes, generator=g)]
    x = class_means[y] + torch.randn(n_nodes, feat_dim, generator=g) + shift

    same = y.view(-1, 1) == y.view(1, -1)
    prob = torch.where(same, torch.tensor(p_in), torch.tensor(p_out))
    upper = torch.triu(torch.rand(n_nodes, n_nodes, generator=g) < prob, diagonal=1)
    src, dst = upper.nonzero(as_tuple=True)
    edge_index = torch.cat([torch.stack([src, dst]), torch.stack([dst, src])], dim=1)
    return Data(x=x, edge_index=edge_index, y=y)


if __name__ == "__main__":
    CONFIG = dict(
        seed=0,
        n_nodes=300,
        feat=8,
        num_classes=3,
        class_sep=1.5,     # distance of each class mean from the origin
        shift=1.5,         # target feature translation (domain shift)
        p_in=0.05,
        p_out=0.005,
        epochs=30,
        lr=1e-3,
        mmd_weight=0.5,
        hidden_channels=32,
        train_ratio=0.6,
        val_ratio=0.2,
        split_seed=42,
    )
    print("config:", json.dumps(CONFIG))
    set_seed(CONFIG["seed"])

    means = make_class_means(CONFIG["num_classes"], CONFIG["feat"],
                             CONFIG["class_sep"], seed=CONFIG["seed"])
    graph_kw = dict(p_in=CONFIG["p_in"], p_out=CONFIG["p_out"])
    source_graph = make_domain_graph(CONFIG["n_nodes"], means, seed=CONFIG["seed"] + 1,
                                     shift=0.0, **graph_kw)
    target_graph = make_domain_graph(CONFIG["n_nodes"], means, seed=CONFIG["seed"] + 2,
                                     shift=CONFIG["shift"], **graph_kw)

    split_kw = dict(
        task_level="node",
        source=source_graph,
        target=target_graph,
        train_ratio=CONFIG["train_ratio"],
        val_ratio=CONFIG["val_ratio"],
        split_seed=CONFIG["split_seed"],
        split_mode="stratified",
    )
    dm = DataManager(batch_size=1, num_workers=0)
    train_src, train_tgt = dm.load("pyg_domains", train=True, **split_kw)
    test_src, test_tgt = dm.load("pyg_domains", train=False, **split_kw)

    def make_model():
        return GNN(
            source_graph, "SAGE", hidden_channels=CONFIG["hidden_channels"], num_layers=2,
            num_classes=CONFIG["num_classes"], pool="none", device="cpu",
        )

    set_seed(CONFIG["seed"])
    model_so = make_model()
    set_seed(CONFIG["seed"] + 1)
    model_mmd = make_model()

    print("Training Source-Only...")
    set_seed(CONFIG["seed"])
    so = SourceOnlyTrainer(model_so, train_src, train_tgt, lr=CONFIG["lr"], device="cpu")
    so.fit(epochs=CONFIG["epochs"])

    print("Training MMD...")
    set_seed(CONFIG["seed"])
    mmd = MMDTrainer(model_mmd, train_src, train_tgt, mmd_weight=CONFIG["mmd_weight"],
                     lr=CONFIG["lr"], device="cpu")
    mmd.fit(epochs=CONFIG["epochs"])

    for name, trainer in [("Source-Only", so), ("MMD", mmd)]:
        r_src = trainer.evaluate(test_src, domain="source-test")
        r_tgt = trainer.evaluate(test_tgt, domain="target-test")
        print(
            f"{name:12s}  src acc={r_src['accuracy']*100:.1f}%  "
            f"tgt acc={r_tgt['accuracy']*100:.1f}%"
        )

    print("Done.")
